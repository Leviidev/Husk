def tag_of(nested):
    return '' if not nested else ' (%s)' % nested

# ---- Java source: skipping strings and comments, matching braces

def code_mask(text):
    """for each character: True where it is code (not inside a string, char literal or comment)"""
    mask = [True] * len(text)
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c == '/' and i + 1 < n and text[i + 1] == '/':
            j = text.find('\n', i); j = n if j < 0 else j
            for k in range(i, j): mask[k] = False
            i = j; continue
        if c == '/' and i + 1 < n and text[i + 1] == '*':
            j = text.find('*/', i + 2); j = n if j < 0 else j + 2
            for k in range(i, j): mask[k] = False
            i = j; continue
        if c in '"\'':
            j = i + 1
            while j < n and text[j] != c:
                j += 2 if text[j] == '\\' else 1
            for k in range(i, min(j + 1, n)): mask[k] = False
            i = j + 1; continue
        i += 1
    return mask

def body_of(text, mask, decl_at):
    """the span (index of '{', index of its '}') of the class body whose declaration starts at decl_at"""
    i = decl_at
    while i < len(text) and not (text[i] == '{' and mask[i]): i += 1
    depth, j = 0, i
    while j < len(text):
        if mask[j]:
            if text[j] == '{': depth += 1
            elif text[j] == '}':
                depth -= 1
                if depth == 0: return i, j
        j += 1
    return i, len(text) - 1

def find_class(text, mask, span, simple):
    """the declaration of class simple directly inside span (a body span, or None for the file's top level)"""
    lo, hi = (span[0] + 1, span[1]) if span else (0, len(text))
    for m in re.finditer(r'\b(class|interface|enum|@interface)\s+%s\b' % re.escape(simple), text[lo:hi]):
        at = lo + m.start()
        if not mask[at]: continue
        depth = 0
        for k in range(lo, at):
            if mask[k]:
                if text[k] == '{': depth += 1
                elif text[k] == '}': depth -= 1
        if depth == 0: return at
    return None

def locate(text, path_names):
    """the body span of a class: the top-level one, then each nested name in turn"""
    mask = code_mask(text)
    span = None
    for name in path_names:
        at = find_class(text, mask, span, name)
        if at is None: return None
        span = body_of(text, mask, at)
    return span

def strip_section(text, nested):
    b = MARK + tag_of(nested) + BEGIN_TAIL
    e = END + tag_of(nested)
    i = text.find(b)
    if i < 0: return text
    line_start = text.rfind('\n', 0, i) + 1
    j = text.find(e, i)
    if j < 0: return text
    j_end = text.find('\n', j); j_end = len(text) if j_end < 0 else j_end + 1
    return text[:line_start] + text[j_end:]

def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    opts = dict(a[2:].split('=', 1) for a in sys.argv[1:] if a.startswith('--') and '=' in a)
    src = args[0]
    fw = {}
    for d in dexes(opts.get('fw', '/Volumes/GTAV/husk2/java/husk-framework.dex')): fw.update(d.classes())
    plat = Plat(opts.get('platform', '/Volumes/GTAV/husk2/aosp/fw/framework.jar').split(','))
    only = set('L%s;' % o for o in opts['only'].split(',')) if 'only' in opts else None
    art = '/Volumes/GTAV/husk2/root/apex/com.android.art/javalib/'
    core = Plat([art + 'core-oj.jar', art + 'core-libart.jar'])       # libcore: what Husk's classes inherit from java.*

    def ok_type(t):
        t = base(t)
        if t in PRIM: return True
        if t.startswith(JDK9): return False
        if t.startswith(('Ljava/', 'Ljavax/')) and not t.startswith('Ljavax/microedition/'): return True
        return t in fw
    # what earlier runs added does not count as Husk's own: read back from the generated sections
    PR = {'int': 'I', 'long': 'J', 'float': 'F', 'double': 'D', 'boolean': 'Z', 'byte': 'B', 'char': 'C', 'short': 'S', 'void': 'V'}
    def to_desc(t):
        dims = 0
        while t.endswith('[]'): dims += 1; t = t[:-2]
        if t in PR: return '[' * dims + PR[t]
        parts = t.split('.')
        for i in range(len(parts), 0, -1):              # the longest package prefix that names a class; the rest is nesting
            cand = 'L' + '/'.join(parts[:i]) + ('$' + '$'.join(parts[i:]) if parts[i:] else '') + ';'
            if cand in plat.cls or cand in fw or cand in core.cls: return '[' * dims + cand
        return '[' * dims + 'L' + t.replace('.', '/') + ';'
    files = []
    for root, dirs, fs in os.walk(src):
        for f in fs:
            if f.endswith('.java'): files.append(os.path.join(root, f))
    generated = {}
    for path in files:
        t = open(path).read()
        if MARK not in t: continue
        top = 'L' + os.path.relpath(path, src)[:-5] + ';'
        for m in re.finditer(re.escape(MARK) + r'(?: \(([\w.]+)\))?' + re.escape(BEGIN_TAIL), t):
            nested = m.group(1)
            e = t.find(END + tag_of(nested), m.end())
            if e < 0: continue
            sec = t[m.end():e]
            c = top if not nested else top[:-1] + '$' + nested.replace('.', '$') + ';'
            keys = set()
            for mm in re.finditer(r'^\s+(?:public |protected |static |final |default |synchronized )*(?:([\w.\[\]]+) )?(\w+)\(([^)]*)\) \{', sec, re.M):
                ps = [p.strip().rsplit(' ', 1)[0] for p in mm.group(3).split(',') if p.strip()]
                name = mm.group(2) if mm.group(1) else '<init>'
                keys.add(name + '(' + ''.join(to_desc(p) for p in ps) + ')')
            for mm in re.finditer(r'^\s+(?:public |protected |static |final )*[\w.\[\]<>]+ (\w+)( = [^;]*)?;', sec, re.M):
                keys.add('field:' + mm.group(1))
            generated[c] = keys
    def husk_has(c, key, field=False):
        """the member on c or any of Husk's superclasses / superinterfaces"""
        seen, todo = set(), [c]
        while todo:
            k = todo.pop()
            if not k or k in seen: continue
            seen.add(k)
            if k not in fw:
                if k not in core.cls: continue
                kfl, ksup, kifs, kfields, kmeths = core.info(k)
                if field and any(f[0] == key for f in kfields): return True
                if not field:
                    n, ps = key[:key.index('(')], key[key.index('('):key.index(')') + 1]
                    if any(mn == n and sg.startswith(ps) for mn, sg, af in kmeths): return True
                todo.append(ksup); todo += kifs
                continue
            sup, ifs, ms, fs = fw[k]
            gen_k = generated.get(k, ())
            if field and key in fs and 'field:' + key not in gen_k: return True
            if not field:
                n, ps = key[:key.index('(')], key[key.index('('):key.index(')') + 1]
                if n + ps not in gen_k and any(m.startswith(n + ps) for m in ms): return True      # Husk's own (another return too)
            todo.append(sup); todo += ifs
        return False
    # what Husk's subclasses declare themselves (maybe package-private): a public one added above them would clash
    below = {}
    for k, (sup, ifs, ms, fs) in fw.items():
        params = {m[:m.index(')') + 1] for m in ms} - generated.get(k, set())
        a, guard = sup, 0
        while a and a in fw and guard < 64:
            below.setdefault(a, set()).update(params)
            a, guard = fw[a][0], guard + 1
    def has_noarg_ctor(c):
        return c in fw and '<init>()V' in fw[c][2]

    def members_for(c, body_text):
        """the lines to add to class c, whose body (without an old section) is body_text"""
        fl, sup, ifs, fields, meths = plat.info(c)
        is_if, is_enum = fl & 0x200, fl & 0x4000
        simple = c[1:-1].rsplit('/', 1)[-1].rsplit('$', 1)[-1]
        lines, have_names = [], set()
        for n, ty, af, v in fields:
            if not af & 5 or af & 0x1000 or af & 0x4000 or not ok_type(ty) or '$' in n: continue
            if husk_has(c, n, field=True) or n in have_names: continue
            if re.search(r'\b%s\b\s*[=;,]' % re.escape(n), body_text): continue    # declared some way the dex lost (constant folding)
            have_names.add(n)
            lit = literal(ty, v) if af & 8 and af & 0x10 else None
            if is_if:
                lines.append('%s %s = %s;' % (jtype(ty), n, lit if lit is not None else DEFAULT.get(ty, 'null')))
                continue
            m = 'public ' if af & 1 else 'protected '
            if af & 8: m += 'static '
            if af & 0x10 and af & 8 and lit is not None: m += 'final '
            lines.append('%s%s %s%s;' % (m, jtype(ty), n, (' = ' + lit) if lit is not None and af & 0x10 else ''))
        # what the source declares by hand counts even before the dex has it (name, parameter types by simple name)
        declared = set()
        for m in re.finditer(r'(?m)(?:^|[;{}])\s*(?:@\w+\s+)*(?:(?:public|protected|private|static|final|synchronized|abstract|native|default)\s+)*[\w.<>\[\]?, ]+?\s+(\w+)\s*\(([^()]*)\)\s*(?:throws [\w., ]+)?\s*[{;]', body_text):
            ps_src = [p for p in re.sub(r'<[^<>]*>', '', re.sub(r'<[^<>]*>', '', m.group(2))).split(',') if p.strip()]
            simple_types = []
            for p in ps_src:
                words = p.replace('final ', '').strip().split()
                t = words[0] if words else ''
                dims = t.count('[]') + (1 if '...' in t else 0) + (words[-1].count('[]') if len(words) >= 2 else 0)
                simple_types.append(t.replace('[]', '').replace('...', '').rsplit('.', 1)[-1] + '[]' * dims)
            declared.add((m.group(1), tuple(simple_types)))
        added, holder, missing = set(), False, []
        for n, sig, af in meths:
            if not af & 5 or af & 0x1040 or n == '<clinit>' or '$' in n: continue        # not lambdas, accessors, ravenwood hooks
            if is_enum and n in ('values', 'valueOf', '<init>'): continue
            ps, r = split_params(sig)
            if not all(ok_type(x) for x in ps + [r]): continue
            key = n + sig
            if key in added or husk_has(c, key): continue
            if n != '<init>' and n + sig[:sig.index(')') + 1] in below.get(c, ()): continue
            if n != '<init>' and (n, tuple(jtype(t).rsplit('.', 1)[-1] for t in ps)) in declared: continue
            if n + sig[:sig.index(')') + 1] in {a[:a.index(')') + 1] for a in added}: continue
            added.add(key)
            missing.append((n, sig, af, ps, r))
        names = {n for n, s, a, p, r in missing}
        for n, sig, af, ps, r in missing:
            params = ', '.join('%s p%d' % (jtype(t), i) for i, t in enumerate(ps))
            if n == '<init>':
                if is_if or not has_noarg_ctor(c): continue
                lines.append('%s%s(%s) { this(); }' % ('public ' if af & 1 else 'protected ', simple, params))
                continue
            m = 'public ' if af & 1 else 'protected '
            if af & 8: m += 'static '
            body = '' if r == 'V' else ' return %s; ' % dflt(r)
            if not af & 8 and r == c: body = ' return this; '                          # a builder's setter chains
            if not af & 8 and not is_if:
                if n.startswith('set') and len(n) > 3 and len(ps) == 1 and r == 'V' and ('get' + n[3:] in names or 'is' + n[3:] in names):
                    body = ' huskFill.put("%s", %s); ' % (n[3:], box(ps[0], 'p0')); holder = True
                elif (n.startswith('get') and len(n) > 3 or n.startswith('is') and len(n) > 2) and not ps and r != 'V' and 'set' + (n[3:] if n.startswith('get') else n[2:]) in names:
                    body = ' return %s; ' % unbox(r, 'huskFill.get("%s")' % (n[3:] if n.startswith('get') else n[2:])); holder = True
            if is_if:
                lines.append('%s%s %s(%s) {%s}' % ('static ' if af & 8 else 'default ', jtype(r), n, params, body))
            else:
                lines.append('%s%s %s(%s) {%s}' % (m, jtype(r), n, params, body))
        if holder: lines.insert(0, 'private final java.util.HashMap<String, Object> huskFill = new java.util.HashMap<>();')
        # a class that had only Java's implicit constructor loses it to the ones added: it is written out
        if any(l.startswith('public %s(' % simple) or l.startswith('protected %s(' % simple) for l in lines) \
                and not re.search(r'(?m)(^|[;{}])\s*((public|protected|private)\s+)?%s\s*\(' % re.escape(simple), body_text):
            lines.insert(0, 'public %s() {}' % simple)
        return lines

    changed = 0
    for path in sorted(files):
        top = 'L' + os.path.relpath(path, src)[:-5] + ';'
        text = open(path).read()
        if text.startswith('// Generated by'): continue                     # a generator's output (GLES*): its generator's business
        if top not in fw: continue
        # the class and the classes nested in it that Husk declares, outermost first
        targets = [top] + sorted((k for k in fw if k.startswith(top[:-1] + '$') and not re.search(r'\$\d', k)), key=lambda k: k.count('$'))
        orig, total = text, 0
        for c in targets:
            if only is not None and c not in only and top not in only: continue
            if c not in plat.cls: continue
            fl = plat.info(c)[0]
            if not fl & 1 or fl & 0x2000: continue                         # public classes; not annotations
            nested = '.'.join(c[len(top) - 1:-1].split('$')[1:]) if c != top else ''
            text = strip_section(text, nested)
            names = [top[1:-1].rsplit('/', 1)[-1]] + (nested.split('.') if nested else [])
            span = locate(text, names)
            if span is None: continue
            # the old sections of classes nested in this one are not this one's own declarations
            body_text = text[span[0] + 1:span[1]]
            lines = members_for(c, body_text)
            if not lines: continue
            # the indentation of the class's members: one level in from its declaration
            decl_line_start = text.rfind('\n', 0, span[0]) + 1
            indent = re.match(r'[ \t]*', text[decl_line_start:]).group(0) + '    '
            before = text[:span[1]].rstrip()
            close_line_start = text.rfind('\n', 0, span[1]) + 1
            tail = text[close_line_start:span[1]]
            closing_indent = tail if tail.strip() == '' else indent[:-4]
            # an enum whose body is only its constants needs the ';' that ends them before any member
            if plat.info(c)[0] & 0x4000:
                depth, semi = 0, False
                for ch in re.sub(r'"(\\.|[^"\\])*"', '""', body_text):
                    if ch == '{': depth += 1
                    elif ch == '}': depth -= 1
                    elif ch == ';' and depth == 0: semi = True; break
                if not semi: lines.insert(0, ';')
            block = '\n' + indent + MARK + tag_of(nested) + BEGIN_TAIL + '\n' + '\n'.join(indent + l for l in lines) + '\n' + indent + END + tag_of(nested) + '\n'
            text = before + block + closing_indent + text[span[1]:]
            total += len(lines)
        if text != orig:
            open(path, 'w').write(text)
            changed += 1
            if total: print('%s: %d members' % (top[1:-1], total))
    print('%d files changed' % changed)

main()
