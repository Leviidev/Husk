"""
fillmembers.py <src-dir> [--fw=husk-framework.dex] [--platform=framework.jar] [--only=android/os/StrictMode,...]

The platform's public and protected members that Husk's hand-written classes (src/), and the classes nested in them, leave out,
written into each class so app bytecode that names them links: methods with their exact signatures (bodies give 0, false or null
back; a set/get pair keeps its value), static constants with the platform's values, other fields as plain fields, and constructors
that call the class's own no-argument one. A member any of Husk's superclasses already has is inherited and left alone, so is one
the source declares by hand (same name and parameter types) and one whose types neither framework has. What is added goes in a
marked section at the end of the class's body (a nested class's has its name in the marker), rewritten on every run:

    // ---- generated by tools/compat/fillmembers.py ...
    // ---- end of generated members
"""
