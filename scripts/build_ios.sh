#!/bin/bash
# Husk: cross-compile QEMU + its minimal dependency set for arm64-apple-ios.
#
# Toolchain setup follows UTM's scripts/build_dependencies.sh (the -target triple,
# the meson cross-file shape, needs_exe_wrapper) because those details are the
# hard-won part. The dependency list does not: Husk builds 5 libraries where UTM
# builds ~25, since we have no spice/gstreamer/virgl/MoltenVK/usb/tpm surface.
#
# Usage: ./scripts/build_ios.sh [stage ...]      (no args = all stages)
#        stages: libffi glib pixman libucontext libslirp qemu
set -uo pipefail

HUSK_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$HUSK_ROOT/third_party/build"
PREFIX="$HUSK_ROOT/build/ios-arm64/sysroot"
LOGS="$HUSK_ROOT/build/logs"
STAMPS="$HUSK_ROOT/build/stamps"
mkdir -p "$PREFIX" "$LOGS" "$STAMPS"

ARCH=arm64
SDK=iphoneos
SDKMINVER="${SDKMINVER:-16.0}"
NCPU="$(sysctl -n hw.ncpu)"

SDKROOT="$(xcrun --sdk $SDK --show-sdk-path)"
SDKVERSION="$(xcrun --sdk $SDK --show-sdk-version)"
CFLAGS_TARGET="-target $ARCH-apple-ios$SDKMINVER"

export CC="$(xcrun --sdk $SDK --find clang) $CFLAGS_TARGET"
export CXX="$(xcrun --sdk $SDK --find clang++) $CFLAGS_TARGET"
export OBJCC="$(xcrun --sdk $SDK --find clang)"
export AR="$(xcrun --sdk $SDK --find ar)"
export NM="$(xcrun --sdk $SDK --find nm)"
export RANLIB="$(xcrun --sdk $SDK --find ranlib)"
export STRIP="$(xcrun --sdk $SDK --find strip)"
export LD="$(xcrun --sdk $SDK --find ld)"

export CFLAGS="-arch $ARCH -isysroot $SDKROOT -I$PREFIX/include $CFLAGS_TARGET -O2"
export CXXFLAGS="$CFLAGS"
export CPPFLAGS="-arch $ARCH -isysroot $SDKROOT -I$PREFIX/include $CFLAGS_TARGET"
export OBJCFLAGS="$CFLAGS"
export LDFLAGS="-arch $ARCH -isysroot $SDKROOT -L$PREFIX/lib $CFLAGS_TARGET"

# Cross pkg-config: look ONLY in our sysroot so host Homebrew libraries can never
# leak into an iOS link.
export PKG_CONFIG="$(command -v pkg-config)"
export PKG_CONFIG_LIBDIR="$PREFIX/lib/pkgconfig:$PREFIX/share/pkgconfig"
unset PKG_CONFIG_PATH

banner() { printf '\n\033[0;32m=== %s ===\033[0m\n' "$*"; }
fail()   { printf '\033[0;31m[FAIL] %s (see %s)\033[0m\n' "$1" "$2"; exit 1; }

done_stage() { [ -f "$STAMPS/$1" ]; }
mark_stage() { touch "$STAMPS/$1"; }

meson_quote() { echo "'$(echo $* | sed "s/ /','/g")'"; }

gen_cross() {
    local cross="$1" system="$2"
    cat > "$cross" <<EOF
# Automatically generated by Husk build_ios.sh - do not edit
[properties]
needs_exe_wrapper = true
[built-in options]
c_args = [$(meson_quote $CFLAGS)]
cpp_args = [$(meson_quote $CXXFLAGS)]
objc_args = [$(meson_quote $OBJCFLAGS)]
objcpp_args = [$(meson_quote $OBJCFLAGS)]
c_link_args = [$(meson_quote $LDFLAGS)]
cpp_link_args = [$(meson_quote $LDFLAGS)]
objc_link_args = [$(meson_quote $LDFLAGS)]
objcpp_link_args = [$(meson_quote $LDFLAGS)]
[binaries]
c = [$(meson_quote $CC)]
cpp = [$(meson_quote $CXX)]
objc = [$(meson_quote $OBJCC)]
objcpp = [$(meson_quote $OBJCC)]
ar = ['$AR']
nm = ['$NM']
ranlib = ['$RANLIB']
strip = ['$STRIP', '-x']
pkg-config = ['$PKG_CONFIG']
pkgconfig = ['$PKG_CONFIG']
python = ['$(command -v python3)']
[host_machine]
system = '$system'
EOF
    if [ "$system" = "darwin" ]; then
        echo "kernel = 'xnu'" >> "$cross"
        echo "subsystem = 'ios'" >> "$cross"
    fi
    cat >> "$cross" <<EOF
cpu_family = 'aarch64'
cpu = 'aarch64'
endian = 'little'
EOF
}

CROSS_IOS="$HUSK_ROOT/build/ios-arm64/cross-ios.meson"
CROSS_DARWIN="$HUSK_ROOT/build/ios-arm64/cross-darwin.meson"
gen_cross "$CROSS_IOS" ios
gen_cross "$CROSS_DARWIN" darwin

# ---------------------------------------------------------------- autotools
build_autotools() {
    local name="$1"; shift
    local dir="$SRC/$name"
    local log="$LOGS/$name.log"
    done_stage "$name" && { echo "[skip] $name"; return 0; }
    banner "building $name (autotools)"
    ( cd "$dir" \
      && ./configure --host=aarch64-apple-darwin --prefix="$PREFIX" \
                     --enable-static --disable-shared "$@" \
      && make -j"$NCPU" \
      && make install ) > "$log" 2>&1 || fail "$name" "$log"
    mark_stage "$name"
}

# ---------------------------------------------------------------- meson
build_meson() {
    local name="$1" cross="$2"; shift 2
    local dir="$SRC/$name"
    local log="$LOGS/$name.log"
    done_stage "$name" && { echo "[skip] $name"; return 0; }
    banner "building $name (meson)"
    rm -rf "$dir/_husk_build"
    ( cd "$dir" \
      && meson setup _husk_build --cross-file "$cross" --prefix="$PREFIX" \
                --buildtype=release --default-library=static "$@" \
      && meson compile -C _husk_build -j "$NCPU" \
      && meson install -C _husk_build ) > "$log" 2>&1 || fail "$name" "$log"
    mark_stage "$name"
}

apply_patch() {
    local dir="$1"
    local patch="$2"
    local stamp="$SRC/$dir/.husk-patched"
    [ -f "$stamp" ] && return 0
    [ -f "$HUSK_ROOT/patches/$patch" ] || return 0
    echo "[patch] $dir <- $patch"
    ( cd "$SRC/$dir" && patch -p1 -N -r - < "$HUSK_ROOT/patches/$patch" ) >/dev/null 2>&1
    touch "$stamp"
}

# ---------------------------------------------------------------- stages
stage_libffi()      { build_autotools libffi-3.5.0; }
stage_glib()        { build_meson glib-2.83.0 "$CROSS_IOS" \
                        -Dtests=false -Dnls=disabled -Dintrospection=disabled \
                        -Dselinux=disabled -Dlibmount=disabled -Ddtrace=disabled \
                        -Dman-pages=disabled -Dglib_debug=disabled -Dxattr=false; }
stage_pixman()      { apply_patch pixman-0.38.0 pixman-0.38.0.patch
                      build_autotools pixman-0.38.0 --disable-gtk --disable-libpng --disable-arm-iwmmxt; }
stage_libucontext() { build_meson libucontext "$CROSS_IOS" -Dfreestanding=true; }
stage_libslirp()    { apply_patch libslirp-v4.9.1 libslirp-v4.9.1.patch
                      build_meson libslirp-v4.9.1 "$CROSS_DARWIN"; }

stage_qemu() {
    local dir="$SRC/qemu-10.0.12-utm"
    local log="$LOGS/qemu.log"
    done_stage qemu && { echo "[skip] qemu"; return 0; }
    apply_patch qemu-10.0.12-utm qemu-10.0.12-utm.patch
    banner "building qemu (this is the long one)"
    rm -rf "$dir/_husk_build"; mkdir -p "$dir/_husk_build"
    ( cd "$dir/_husk_build" \
      && ../configure \
            --prefix="$PREFIX" \
            --cross-prefix="" \
            --target-list=aarch64-softmmu \
            --enable-shared-lib \
            --with-coroutine=libucontext \
            --enable-slirp \
            --disable-cocoa --disable-sdl --disable-gtk --disable-coreaudio \
            --disable-vnc --disable-spice --disable-opengl --disable-virglrenderer \
            --disable-curses --disable-curl --disable-libusb --disable-usb-redir \
            --disable-tpm --disable-docs --disable-guest-agent --disable-tools \
            --disable-hvf --disable-vde --disable-brlapi --disable-libssh \
            --disable-bzip2 --disable-snappy --disable-lzo --disable-gnutls \
            --disable-png --disable-vte --disable-zstd \
            --disable-nettle --disable-gcrypt --disable-auth-pam \
            --disable-install-blobs --disable-sparse --disable-debug-info \
            --extra-cflags="$CFLAGS" --extra-ldflags="$LDFLAGS" \
      && make -j"$NCPU" ) > "$log" 2>&1 || fail qemu "$log"
    husk_stage_dylib
    mark_stage qemu
}

# Incremental QEMU rebuild: keeps the existing build dir but re-runs ninja under
# the full cross environment. Meson will reconfigure itself if meson.build changed,
# and it MUST see our PKG_CONFIG_LIBDIR when it does -- reconfiguring with the host
# environment silently re-detects Homebrew's macOS libraries and the link then fails
# with "building for 'iOS', but linking in dylib built for 'macOS'".
stage_qemurebuild() {
    local dir="$SRC/qemu-10.0.12-utm"
    local log="$LOGS/qemu-rebuild.log"
    banner "rebuilding qemu (incremental)"
    ( cd "$dir/_husk_build" && ninja libqemu-aarch64-softmmu.dylib ) > "$log" 2>&1 \
        || fail qemu-rebuild "$log"
    echo "[ok  ] $(ls -lh "$dir/_husk_build/libqemu-aarch64-softmmu.dylib" | awk '{print $5}')"
    husk_stage_dylib
}

# Copy the built dylib somewhere stable. The Xcode project points here, not into
# QEMU's meson build directory, so regenerating or relocating that build does not
# break the app target.
husk_stage_dylib() {
    local src="$SRC/qemu-10.0.12-utm/_husk_build/libqemu-aarch64-softmmu.dylib"
    [ -f "$src" ] || return 0
    mkdir -p "$PREFIX/../lib"
    cp "$src" "$PREFIX/../lib/"
    echo "[stage] $(cd "$PREFIX/../lib" && pwd)/libqemu-aarch64-softmmu.dylib"
}

STAGES=("$@")
[ ${#STAGES[@]} -eq 0 ] && STAGES=(libffi glib pixman libucontext libslirp qemu)

echo "HUSK build: PREFIX=$PREFIX"
echo "            SDK=$SDKROOT ($SDKVERSION), min=$SDKMINVER, ncpu=$NCPU"
for s in "${STAGES[@]}"; do "stage_$s"; done
banner "build complete"
ls -la "$PREFIX/lib" 2>/dev/null | head -20
