package android.graphics.drawable;

import android.graphics.*;
import java.util.ArrayList;

/** An &lt;animated-vector&gt;: its vector drawn as it stands (the animators' targets are not run), with Animatable2's
 *  start/stop and callbacks so code that drives the animation (a checkbox's tick, a progress spinner's morph) works. */
public class AnimatedVectorDrawable extends Drawable implements Animatable2, Drawable.Callback {
    private Drawable mVector;
    private boolean mRunning;
    private final ArrayList<Animatable2.AnimationCallback> mCallbacks = new ArrayList<>();

    public AnimatedVectorDrawable() {}
    /** ResInflate: the &lt;animated-vector&gt;'s android:drawable. */
    public AnimatedVectorDrawable(Drawable vector) { setVector(vector); }
    private void setVector(Drawable d) { mVector = d; if (d != null) { d.setCallback(this); d.setBounds(getBounds()); } }

    @Override public void draw(Canvas c) { if (mVector != null) mVector.draw(c); }
    @Override protected void onBoundsChange(Rect b) { if (mVector != null) mVector.setBounds(b); }
    @Override public int getIntrinsicWidth() { return mVector == null ? -1 : mVector.getIntrinsicWidth(); }
    @Override public int getIntrinsicHeight() { return mVector == null ? -1 : mVector.getIntrinsicHeight(); }
    @Override public void setAlpha(int a) { if (mVector != null) mVector.setAlpha(a); }
    @Override public int getAlpha() { return mVector == null ? 255 : mVector.getAlpha(); }
    @Override public void setColorFilter(ColorFilter f) { if (mVector != null) mVector.setColorFilter(f); }
    @Override public ColorFilter getColorFilter() { return mVector == null ? null : mVector.getColorFilter(); }
    @Override public void setTintList(android.content.res.ColorStateList t) { if (mVector != null) mVector.setTintList(t); }
    @Override public void setTintMode(PorterDuff.Mode m) { if (mVector != null) mVector.setTintMode(m); }
    @Override public int getOpacity() { return PixelFormat.TRANSLUCENT; }
    @Override public boolean isStateful() { return mVector != null && mVector.isStateful(); }
    @Override protected boolean onStateChange(int[] s) { return mVector != null && mVector.setState(s); }
    @Override public Drawable mutate() { if (mVector != null) mVector.mutate(); return this; }
    @Override public void applyTheme(android.content.res.Resources.Theme t) { if (mVector != null) mVector.applyTheme(t); }
    @Override public boolean canApplyTheme() { return mVector != null && mVector.canApplyTheme(); }
    @Override public void getOutline(Outline o) { if (mVector != null) mVector.getOutline(o); }
    @Override public ConstantState getConstantState() {
        final Drawable v = mVector;
        return new ConstantState() {
            @Override public Drawable newDrawable() { return new AnimatedVectorDrawable(v != null && v.getConstantState() != null ? v.getConstantState().newDrawable() : v); }
            @Override public int getChangingConfigurations() { return 0; }
        };
    }

    // ---- Animatable2: the animation runs in no time
    @Override public void start() {
        if (mRunning) return;
        mRunning = true;
        for (Animatable2.AnimationCallback cb : new ArrayList<>(mCallbacks)) cb.onAnimationStart(this);
        scheduleSelf(this::finish, android.os.SystemClock.uptimeMillis());
    }
    private void finish() {
        if (!mRunning) return;
        mRunning = false;
        invalidateSelf();
        for (Animatable2.AnimationCallback cb : new ArrayList<>(mCallbacks)) cb.onAnimationEnd(this);
    }
    @Override public void stop() { finish(); }
    @Override public boolean isRunning() { return mRunning; }
    public void reset() { mRunning = false; invalidateSelf(); }
    public void reverse() { start(); }
    public boolean canReverse() { return true; }
    public long getTotalDuration() { return 0; }
    @Override public void registerAnimationCallback(Animatable2.AnimationCallback cb) { if (cb != null && !mCallbacks.contains(cb)) mCallbacks.add(cb); }
    @Override public boolean unregisterAnimationCallback(Animatable2.AnimationCallback cb) { return mCallbacks.remove(cb); }
    @Override public void clearAnimationCallbacks() { mCallbacks.clear(); }

    public void invalidateDrawable(Drawable who) { invalidateSelf(); }
    public void scheduleDrawable(Drawable who, Runnable what, long when) { scheduleSelf(what, when); }
    public void unscheduleDrawable(Drawable who, Runnable what) { unscheduleSelf(what); }
    // ---- generated by tools/compat/fillmembers.py: the platform's members this class does not write (signatures only)
    public void clearMutated() {}
    public void forceAnimationOnUI() {}
    // ---- end of generated members
}
