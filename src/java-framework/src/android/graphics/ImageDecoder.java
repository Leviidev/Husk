    private static byte[] read(Source s) throws IOException {
        try { return s.bytes(); }
        catch (IOException e) { throw new DecodeException(DecodeException.SOURCE_EXCEPTION, "Failed to read the source", e, s); }
    }

    public static ImageInfo decodeHeader(Source s) throws IOException {
        byte[] b = read(s);
        BitmapFactory.Options o = new BitmapFactory.Options();
        o.inJustDecodeBounds = true;
        BitmapFactory.decodeByteArray(b, 0, b.length, o);
        if (o.outWidth <= 0 || o.outHeight <= 0) throw new DecodeException(DecodeException.SOURCE_MALFORMED_DATA, "Failed to create image decoder with message 'unimplemented'Input contained an error.", null, s);
        return new ImageInfo(o.outWidth, o.outHeight, o.outMimeType);
    }

    public static Bitmap decodeBitmap(Source s) throws IOException { return decodeBitmap(s, null); }
    public static Bitmap decodeBitmap(Source s, OnHeaderDecodedListener l) throws IOException {
        byte[] b = read(s);
        BitmapFactory.Options o = new BitmapFactory.Options();
        o.inJustDecodeBounds = true;
        BitmapFactory.decodeByteArray(b, 0, b.length, o);
        if (o.outWidth <= 0 || o.outHeight <= 0) throw new DecodeException(DecodeException.SOURCE_MALFORMED_DATA, "Failed to create image decoder with message 'unimplemented'Input contained an error.", null, s);
        ImageDecoder d = new ImageDecoder(s, new ImageInfo(o.outWidth, o.outHeight, o.outMimeType));
        if (l != null) l.onHeaderDecoded(d, d.mInfo, s);
        // the largest power-of-two sample that stays at or above the target, then an exact scale
        int sample = 1;
        while (o.outWidth / (sample * 2) >= d.mTargetW && o.outHeight / (sample * 2) >= d.mTargetH) sample *= 2;
        BitmapFactory.Options decode = new BitmapFactory.Options();
        decode.inSampleSize = sample;
        Bitmap bm = BitmapFactory.decodeByteArray(b, 0, b.length, decode);
        if (bm == null) throw new DecodeException(DecodeException.SOURCE_MALFORMED_DATA, "Failed to decode the image", null, s);
        if (bm.getWidth() != d.mTargetW || bm.getHeight() != d.mTargetH) {
            Bitmap scaled = Bitmap.createScaledBitmap(bm, d.mTargetW, d.mTargetH, true);
            if (scaled != bm) bm.recycle();
            bm = scaled;
        }
        if (d.mCrop != null) {
            Rect c = new Rect(d.mCrop);
            if (!c.intersect(0, 0, bm.getWidth(), bm.getHeight()) || c.isEmpty()) throw new IllegalStateException("Subset " + d.mCrop + " not contained by scaled image bounds: (" + bm.getWidth() + " x " + bm.getHeight() + ")");
            Bitmap cropped = Bitmap.createBitmap(bm, c.left, c.top, c.width(), c.height());
            if (cropped != bm) bm.recycle();
            bm = cropped;
        }
        if (d.mPost != null || d.mMutable) {
            if (!bm.isMutable()) { Bitmap m = bm.copy(Bitmap.Config.ARGB_8888, true); bm.recycle(); bm = m; }
            if (d.mPost != null) d.mPost.onPostProcess(new Canvas(bm));
        }
        android.content.res.Resources r = s.resources();
        if (r != null) bm.setDensity(r.getDisplayMetrics().densityDpi);
        return bm;
    }

    public static Drawable decodeDrawable(Source s) throws IOException { return decodeDrawable(s, null); }
    public static Drawable decodeDrawable(Source s, OnHeaderDecodedListener l) throws IOException {
        Bitmap bm = decodeBitmap(s, l);
        android.content.res.Resources r = s.resources();
        return r != null ? new BitmapDrawable(r, bm) : new BitmapDrawable(bm);
    }

    public static boolean isMimeTypeSupported(String mime) {
        if (mime == null) throw new NullPointerException("mimeType");
        switch (mime.toLowerCase(java.util.Locale.ROOT)) {
            case "image/png": case "image/jpeg": case "image/webp": case "image/gif": case "image/bmp": case "image/x-ico": case "image/vnd.wap.wbmp": case "image/heif": case "image/heic": return true;
        }
        return false;
    }
