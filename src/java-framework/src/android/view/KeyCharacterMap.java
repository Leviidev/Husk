    public static int huskChar(int code, boolean shift) {
        if (code >= KeyEvent.KEYCODE_A && code <= KeyEvent.KEYCODE_Z) return (shift ? 'A' : 'a') + code - KeyEvent.KEYCODE_A;
        if (code >= KeyEvent.KEYCODE_0 && code <= KeyEvent.KEYCODE_9) return KEYS.charAt(2 * (code - KeyEvent.KEYCODE_0) + (shift ? 1 : 0));
        if (code == KeyEvent.KEYCODE_STAR) return '*';
        if (code == KeyEvent.KEYCODE_POUND) return '#';
        if (code == KeyEvent.KEYCODE_AT) return '@';
        if (code == KeyEvent.KEYCODE_PLUS) return '+';
        for (int[] k : OTHER) if (k[0] == code) return shift ? k[2] : k[1];
        return 0;
    }
