    public static int getAbsoluteGravity(int gravity, int layoutDirection) {
        int r = gravity;
        if ((r & RELATIVE_LAYOUT_DIRECTION) > 0) {
            if ((r & START) == START) { r &= ~START; r |= LEFT; }
            else if ((r & END) == END) { r &= ~END; r |= RIGHT; }
            r &= ~RELATIVE_LAYOUT_DIRECTION;
        }
        return r;
    }
