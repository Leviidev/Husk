package android.net.http;

import java.security.cert.CertificateException;
import java.security.cert.X509Certificate;
import java.util.Arrays;
import java.util.List;
import javax.net.ssl.X509TrustManager;

/** A trust manager's host-aware check (Cronet and OkHttp's certificate pinning use it): conscrypt's TrustManagerImpl answers with the
 *  verified chain; any other trust manager checks the chain and it is returned as given. */
public class X509TrustManagerExtensions {
    private final X509TrustManager mTm;
    private final java.lang.reflect.Method mHostCheck;
    public X509TrustManagerExtensions(X509TrustManager tm) throws IllegalArgumentException {
        if (tm == null) throw new IllegalArgumentException("tm == null");
        mTm = tm;
        java.lang.reflect.Method m = null;
        try { m = tm.getClass().getMethod("checkServerTrusted", X509Certificate[].class, String.class, String.class); } catch (NoSuchMethodException e) {}
        mHostCheck = m;
    }
    @SuppressWarnings("unchecked")
    public List<X509Certificate> checkServerTrusted(X509Certificate[] chain, String authType, String host) throws CertificateException {
        if (mHostCheck != null) {
            try {
                Object r = mHostCheck.invoke(mTm, chain, authType, host);
                if (r instanceof List) return (List<X509Certificate>) r;
            } catch (java.lang.reflect.InvocationTargetException e) {
                Throwable c = e.getCause();
                if (c instanceof CertificateException) throw (CertificateException) c;
                if (c instanceof RuntimeException) throw (RuntimeException) c;
                throw new CertificateException(c);
            } catch (IllegalAccessException e) { /* the plain check below */ }
        }
        mTm.checkServerTrusted(chain, authType);
        return Arrays.asList(chain);
    }
    public boolean isUserAddedCertificate(X509Certificate cert) { return false; }
    public boolean isSameTrustConfiguration(String hostname1, String hostname2) { return true; }
    // ---- generated by tools/compat/fillmembers.py: the platform's members this class does not write (signatures only)
    public java.util.List checkServerTrusted(java.security.cert.X509Certificate[] p0, byte[] p1, byte[] p2, java.lang.String p3, java.lang.String p4) { return new java.util.ArrayList(); }
    // ---- end of generated members
}
