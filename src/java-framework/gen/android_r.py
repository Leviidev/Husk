"""
android_r.py <framework-res resources.arsc> <src dir>: android.R (the public resources, ids as the platform has them, which apps compile
in) and husk.IR (every framework resource, for Husk's own widgets, as com.android.internal.R is for the platform's).
"""
import keyword, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import arsc

JAVA_KW = set('abstract assert boolean break byte case catch char class const continue default do double else enum extends final finally float for goto if implements import instanceof int interface long native new package private protected public return short static strictfp super switch synchronized this throw throws transient try void volatile while true false null'.split())

def ident(n):
    import re
    n = re.sub(r'[^A-Za-z0-9_$]', '_', n)
    if n[:1].isdigit(): n = '_' + n
    return n + '_' if n in JAVA_KW else n

def gen(arsc_path, src, cls, pkg_name, public_only):
    _, pk = arsc.read(arsc_path)
    p = pk[0]
    by_type = {}
    for (tid, e), key in p.entries.items():
        if p.types[tid].startswith('^'): continue
        flags = p.spec.get(tid, [])
        pub = e < len(flags) and flags[e] & arsc.SPEC_PUBLIC
        if public_only and not pub: continue
        by_type.setdefault(p.types[tid], {})[ident(key)] = (p.id << 24) | (tid << 16) | e
    pkg, name = cls.rsplit('.', 1)
    out = ['// Generated by src/java-framework/gen/android_r.py from framework-res; do not edit.', 'package %s;' % pkg, '',
           'public final class %s {' % name]
    for t in sorted(by_type):
        out.append('    public static final class %s {' % ident(t))
        for k, v in sorted(by_type[t].items(), key=lambda kv: kv[1]):
            out.append('        public static final int %s = 0x%08x;' % (k, v))
        out.append('    }')
    out.append('}')
    path = os.path.join(src, *pkg.split('.'), name + '.java')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w').write('\n'.join(out) + '\n')
    return sum(len(v) for v in by_type.values())

if __name__ == '__main__':
    a, src = sys.argv[1], sys.argv[2]
    print('android.R', gen(a, src, 'android.R', 'android', True))
    print('husk.IR', gen(a, src, 'husk.IR', 'android', False))
