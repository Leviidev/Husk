"""styleables.py <framework-res resources.arsc> <spec> <out.java>: husk.S, the attribute arrays Husk's widgets read (sorted by id, as obtainStyledAttributes wants)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import arsc
a, spec, out = sys.argv[1:4]
_, pk = arsc.read(a)
p = pk[0]
attr_t = p.types.index('attr')
ids = {key: (p.id << 24) | (attr_t << 16) | e for (t, e), key in p.entries.items() if t == attr_t}
lines = ['// Generated by src/java-framework/gen/styleables.py from gen/styleables.txt; do not edit.', 'package husk;', '',
         '/** The attribute arrays Husk\'s widgets read (as com.android.internal.R.styleable is for the platform\'s). */', 'public final class S {']
for line in open(spec):
    line = line.strip()
    if not line or line.startswith('#'): continue
    name, attrs = line.split(':', 1)
    names = []
    for n in attrs.split():
        if n not in ids: print('missing attr', n, 'in', name, file=sys.stderr); continue
        if n not in names: names.append(n)
    names.sort(key=lambda n: ids[n])
    lines.append('    public static final int[] %s = { %s };' % (name, ', '.join('0x%08x' % ids[n] for n in names)))
    for i, n in enumerate(names):
        lines.append('    public static final int %s_%s = %d;' % (name, n, i))
lines.append('}')
open(out, 'w').write('\n'.join(lines) + '\n')
